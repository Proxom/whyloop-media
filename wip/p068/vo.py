# Kokoro-82M q8 (Apache-2.0) voiceover, one wav per line. usage: <venv>/python vo.py <ttsdir> <outdir>
import sys, json, soundfile as sf
from kokoro_onnx import Kokoro
TTS = sys.argv[1]; OUT = sys.argv[2]
LINES = [
 "How does a scale know the weight?",
 "Inside: two springs, a toothed rack, and a small gear.",
 "Hang two kilos. The weight pulls down and stretches the springs.",
 "The rack slides down with them. Its teeth turn the gear, and the gear turns the needle.",
 "Twice the weight, twice the stretch. That's why the marks are evenly spaced.",
 "The springs feel the weight. The gear just reads it.",
]
k = Kokoro(f'{TTS}/model_q8.onnx', f'{TTS}/voices.npz')
info = []
for i, L in enumerate(LINES):
    s, sr = k.create(L, voice='af_heart', speed=1.1, lang='en-us')
    sf.write(f'{OUT}/vo{i}.wav', s, sr); info.append({'i': i, 'text': L, 'dur': round(len(s) / sr, 3)})
json.dump(info, open(f'{OUT}/vo.json', 'w'), indent=1); print(json.dumps(info, indent=0))
